/** Build one production race default from the Avatar catalog. */
export function buildRaceDefault(race: RaceId): VoxelRaceDefault {
  const def = raceDef(race);
  const config = defaultConfig(race);
  const body = RACE_BODY[race];
  const skinTone = skinToneOf(config);
  return {
    id: race,
    avatarId: `avatar-${race}`,
    label: def.label,
    blurb: def.blurb,
    config,
    code: encodeConfig(config),
    look: {
      skin: cssHex(skinTone),
      shirt: body.look.shirt,
      pants: body.look.pants,
      hat: body.look.hat,
      hatColor: body.look.hatColor,
      cape: body.look.cape,
      capeColor: body.look.capeColor,
      avatarHead: true,
    },
    heightM: body.heightM,
    classHint: body.classHint,
    portraitPath: `avatar/races/${race}-portrait.png`,
    facePath: `avatar/races/${race}-face.png`,
    skinTone,
    kind: "voxel-avatar-race",
    renderPipeline: "voxel",
  };
}

/** All six production race defaults (stable order matches {@link RACES}). */
export function listRaceDefaults(): VoxelRaceDefault[] {
  return RACES.map((r) => buildRaceDefault(r.id));
}

export function raceDefault(id: RaceId): VoxelRaceDefault {
  return buildRaceDefault(id);
}

/** Fleet manifest shape written to `public/avatar/races/defaults.json`. */
export interface VoxelRaceDefaultsManifest {
  version: 1;
  kind: "voxel-avatar-race-defaults";
  source: "avatar-edit-catalog";
  note: string;
  races: VoxelRaceDefault[];
}

export function buildRaceDefaultsManifest(): VoxelRaceDefaultsManifest {
  return {
    version: 1,
    kind: "voxel-avatar-race-defaults",
    source: "avatar-edit-catalog",
    note:
      "Default playable voxel race characters from Avatar Edit (6 modular cube races). " +
      "Use config + look with Explorer/VoxelCharacter; not grudge6, not free-rpg TPose.",
    races: listRaceDefaults(),
  };
}

/** localStorage key for the published 6-race package (per-browser fleet seed). */
export const RACE_DEFAULTS_STORE_KEY = "avatarEdit:raceDefaults:v1";

/** Persist all six race defaults into localStorage for voxel games on this origin. */
export function saveRaceDefaultsToStorage(races: VoxelRaceDefault[] = listRaceDefaults()): void {
  try {
    localStorage.setItem(
      RACE_DEFAULTS_STORE_KEY,
      JSON.stringify({ version: 1, races, savedAt: Date.now() }),
    );
  } catch {
    /* storage blocked */
  }
}

/** Load published race defaults from localStorage; null when missing. */
export function loadRaceDefaultsFromStorage(): VoxelRaceDefault[] | null {
  try {
    const raw = localStorage.getItem(RACE_DEFAULTS_STORE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as { races?: VoxelRaceDefault[] };
    if (!Array.isArray(parsed.races) || parsed.races.length === 0) return null;
    return parsed.races;
  } catch {
    return null;
  }
}

/**
 * Ensure the player has a saved head: use existing save, else seed the race
 * default (human when race unknown). Returns the config that should be worn.
 */
export function ensureRaceHeadConfig(
  race: RaceId = "human",
  loadSaved: () => AvatarConfig | null,
  saveSaved: (cfg: AvatarConfig) => void,
): AvatarConfig {
  const existing = loadSaved();
  if (existing) return existing;
  const cfg = defaultConfig(race);
  saveSaved(cfg);
  return cfg;
}
