/**
 * Production default voxel race characters — built from Avatar Edit's
 * 6-race catalog (`defaultConfig`) plus Explorer box-body looks.
 *
 * These are the fleet SSOT for "pick a race and play" in voxel games
 * (Animator, VoxGrudge openworld, GRUDOX). Not grudge6 Toon RTS kits and
 * not free-rpg TPose GLBs — the modular cube avatar system only.
 *
 * Ship path: `public/avatar/races/defaults.json` (written by
 * `scripts/export-voxel-race-defaults.mjs`). Games may import this module
 * or fetch the JSON.
 */
import {
  RACES,
  defaultConfig,
  encodeConfig,
  raceDef,
  skinToneOf,
  type AvatarConfig,
  type RaceId,
} from "./catalog";

/** CSS hex for Explorer {@link CharacterLook} fields. */
function cssHex(n: number): string {
  return "#" + (n >>> 0).toString(16).padStart(6, "0");
}

/** Body kit that matches a race head so the full voxel reads as one character. */
export interface VoxelRaceBodyLook {
  skin: string;
  shirt: string;
  pants: string;
  hat: "none" | "cap" | "horns" | "ledMask";
  hatColor: string;
  cape: boolean;
  capeColor: string;
  /** Always true for race defaults — head comes from AvatarConfig. */
  avatarHead: true;
}

export interface VoxelRaceDefault {
  /** Race id — same as AvatarConfig.race. */
  id: RaceId;
  /** Fleet avatar id for saves / handoffs (`avatar-human`, …). */
  avatarId: string;
  label: string;
  blurb: string;
  /** Full Avatar Edit build (modular cube head). */
  config: AvatarConfig;
  /** Share code (AV1.…). */
  code: string;
  /** Explorer box-body colours (SI voxel rig). */
  look: VoxelRaceBodyLook;
  /** Target height in metres (1 unit = 1 m). */
  heightM: number;
  /** Soft class hint for loadouts / openworld pickers. */
  classHint: "melee" | "ranged" | "magic" | "rogue";
  /** Relative portrait path under public/ (generated by export script). */
  portraitPath: string;
  /** Relative face PNG path (16×16 nearest scale). */
  facePath: string;
  /** Packed skin tone 0xRRGGBB. */
  skinTone: number;
  /** Kind tag so consumers never confuse with grudge6. */
  kind: "voxel-avatar-race";
  renderPipeline: "voxel";
}

